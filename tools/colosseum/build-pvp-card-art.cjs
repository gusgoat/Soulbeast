const {existsSync, readFileSync, writeFileSync}=require('node:fs');
const {resolve}=require('node:path');

const root=resolve(__dirname,'../..');
const read=path=>readFileSync(resolve(root,path),'utf8');
const menu=read('tools/town-walk-demo/menu.html');
const actors=JSON.parse(menu.match(/const MOTION_ACTORS=(\[[^\r\n]+?\]);/)[1]);
const party=JSON.parse(read('tools/labyrinth-demo/party-art.js').trim().replace(/^window\.PartyArt=/,'').replace(/;$/,''));
const poses={},portraits={};
const asset=path=>path&&existsSync(resolve(root,path))?'/'+path:undefined;

for(const actor of actors){
 const key=actor.kind==='player'?`${actor.cls}-${actor.gender}`:actor.kind==='transform'?`form:${actor.id}`:
  !actor.kind?`${actor.species||actor.id}:${actor.form||0}`:null;
 if(!key)continue;
 const pose={motion:actor.idleMode};
 for(const phase of ['idle','windup','melee','hit','threat','power','meleeEffect']){
  const path=asset(actor.assets[phase]);
  if(path)pose[phase]=path;
 }
 const source=actor.source?.anchor;
 if(source)pose.origin=[source.x,source.y];
 if(actor.windupDuration)pose.windupDuration=actor.windupDuration;
 poses[key]=pose;
}
for(const [species,entry] of Object.entries(party)){
 const base=asset(entry.image)||asset(`assets/beasts/solar/${species}.webp`);
 const forms=(entry.forms||[]).map((path,form)=>asset(path)||(form===0?base:undefined));
 if(base&&!forms.length)forms.push(base);
 if(forms.some(Boolean))portraits[species]=forms;
}

const entries=map=>Object.entries(map).map(([key,value])=>` ${JSON.stringify(key)}:${JSON.stringify(value)}`).join(',\n');
const generated='// Generated by build-pvp-card-art.cjs from the main game battle art.\n';
const output=generated+`export default {\n${entries(poses)}\n};\nexport const beastPortraits={\n${entries(portraits)}\n};\n`;
writeFileSync(resolve(__dirname,'pvp-card-art.mjs'),output);
