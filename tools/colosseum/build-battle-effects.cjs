// Generate the standalone renderer from the walking game's forest and world-boss effects.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.join(__dirname, '../..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r/g, '');
const menu = read('tools/town-walk-demo/menu.html');
function section(start, end, source = menu) {
 const a = source.indexOf(start);
 const b = source.indexOf(end, a + start.length);
 if (a < 0 || b < 0) throw Error('Missing battle renderer section: ' + start);
 return source.slice(a, b).trimEnd();
}

const game = vm.runInNewContext(section('const SoulbeastContent=', '/* ================= CORE STATS') +
 '\n;SoulbeastContent');
const engine = vm.runInNewContext(read('tools/hemant-walk-demo/war-engine.generated.js')
 .replace('skill:pvpSkill,act,', 'skill:pvpSkill,allSkills:()=>SK,act,') +
 '\n;SoulbeastColosseumEngine()', {structuredClone, TextEncoder, TextDecoder});
const skills = Object.fromEntries(Object.entries({...game.SK(), ...engine.allSkills()}).map(([id, sk]) => [
 id, Object.fromEntries(['n','t','el','pw','basePower','hits','mp','tg','ct','summon','rev','revAll','immune','taunt','enchant','all']
  .filter(key => sk[key] !== undefined).map(key => [key, sk[key]]))
]));
const classes = Object.fromEntries(Object.entries(game.CLS()).map(([id, cls]) => [
 id, {base:engine.career(id)?.base || id, sk:cls.sk}
]));
const solar = JSON.parse(section('definitions:[{"id":"solar_pentadrake"', '\n install(){for(const b of this.definitions)')
 .slice('definitions:'.length).replace(/,$/, ''));
for (const beast of solar) for (const skill of beast.skills) skills[skill.id] ??= skill.definition;

const helpers = section('const SIGNATURE_VFX=', 'function spellScene(L,e)')
 .replace('BattleSpeed.ms(life+60)', 'life+60');
const themes = section('const SIGNATURE_EFFECT_THEMES=', 'function signatureEffectProfile');
const renderer = section('const BattleEffects={', ' // Old online/replay packets')
 .replace('const BattleEffects={', 'function renderer(){return {')
 .replace(/\s*const arena=from\.node\.closest[^\n]+\n[^\n]+/, '\n  const box=from.board;')
 .replace("image.src=art.path", "image.src=assetUrl(art.path)")
 .replace(',screen=S.screen;let animation', ';let animation')
 .replace('cleanup.stale=()=>S.screen!==screen||!from.node.isConnected||!to.node.isConnected;', '');
const effects = section(' spawn(L,shape', ' flush(){\n', menu.slice(menu.indexOf('const BattleEffects={')))
 .replace("const screen=S.screen;let done", "let done")
 .replace('cleanup.stale=()=>S.screen!==screen||!from.node.isConnected||!to.node.isConnected;', '')
 .replace(/const arena=to\.node\.closest[^;]+;const shell=/, 'const box=to.board;const shell=')
 .replace(/n\.src=([^;]+);n\.alt=/, 'n.src=assetUrl($1);n.alt=');
const out = `// Generated by build-battle-effects.cjs. Source: the forest and world-boss renderer in menu.html.
const SK=${JSON.stringify(skills)};
const CLS=${JSON.stringify(classes)};
const EL=${JSON.stringify(game.EL())};
const SIGNATURE_ART=${JSON.stringify(game.SIGNATURE_ART())};
const solarLegends=${JSON.stringify(Object.fromEntries(solar.map(beast => [beast.id,beast.theme])))};
const baseOf=id=>CLS[id]?.base;
const CharacterMotion={landed:e=>e.k==='hit'&&e.motionLanded!==false&&!e.miss&&!e.blocked&&!e.immune};
const assetUrl=path=>new URL('../../'+path,import.meta.url).href;
function skillPicture(_actor,sk,id){
 if(!/^[\\w-]+$/.test(id))return '';
 const art=new URL('../../assets/skills/painted-v2/'+id+'.webp',import.meta.url);
 return '<span class="skill-picture skill-painted" style="--skill-image:url('+art+')"><i class="skill-paint skill-individual skill-raster"></i></span>';
}
${helpers}
${themes}
${renderer}
${effects}
};}

export function battleEffects(layer,after){
 const vfx=renderer();
 Object.assign(vfx.legends,solarLegends);
 vfx.later=after;
 return {
  clear(){for(const dispose of [...vfx.live])dispose();layer.replaceChildren();},
  profile(id,actor){return vfx.profile(id,actor);},
  skillByName(name){return Object.keys(SK).find(id=>SK[id].n===name)||'attack';},
  motion(id,profile){
   if(['buff','heal','rest','revert','form','summon','debuff','status'].includes(SK[id]?.t)||SK[id]?.summon)return 'support';
   if(id==='attack')return 'melee';
   return profile.painted?.asset==='crescent'?'blade':profile.mode==='melee'?'melee':'ranged';
  },
  cast(profile,at){
   if(!at||profile.id==='attack')return;
   if(profile.effect){vfx.eclipseCast(layer,at,profile);return;}
   spellBurst(layer,{k:'cast',skill:profile.id},at.x,at.y);
  },
  travel(profile,from,to,actor,target){
   vfx.currentSource=actor;
   vfx.currentTarget=target;
   return vfx.travel(layer,from,to,{...profile,mode:profile.mode==='beam'?'beam':'projectile'});
  },
  impact(profile,event,at,actor){
   vfx.actor=()=>actor;
   const data={...event,skill:profile.id};
   if(event.k==='miss')vfx.spawn(layer,'target',at.x,at.y,{...profile,color:'#9a97ab'});
   else vfx.impact(layer,data,at,profile);
  }
 };
}
`;
fs.writeFileSync(path.join(__dirname, 'battle-effects.generated.mjs'), out.replace(/[^\S\n]+$/gm, ''));
